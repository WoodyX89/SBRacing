/** Fallback description when a specific trail isn't in the table */
window.getTrailDescription = function (name, area, difficulty) {
  var info = window.TRAIL_INFO && window.TRAIL_INFO[name];
  if (info && info.desc) return info;
  var areaLabel = area || "the local network";
  var diff = (difficulty || "intermediate").toLowerCase();
  var generic =
    "Local " + diff + " singletrack in " + areaLabel +
    ". Part of the Medicine Hat / Redcliff / Cypress Hills trail system maintained by the 670 Collective and partners. Check recent conditions on Trailforks before you ride.";
  return {
    desc: generic,
    area: areaLabel,
    photos: ["assets/trails/photos/mh-jump.jpg", "assets/trails/photos/flow-berm.jpg"]
  };
};
